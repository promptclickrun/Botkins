#!/usr/bin/env node
// Writes the brand icons of the apps catalog (desktop/mcp-catalog.mjs) from one pinned release of
// Simple Icons (https://github.com/simple-icons/simple-icons, CC0-1.0): a monochrome SVG path and the
// official hex color per brand. It downloads the release's npm tarball into a temp folder (nothing is
// added to package.json), takes the icons the table below names, and writes the same data file to
// both apps:
//
//   mobile/src/data/appIcons.generated.ts
//   desktop/src/appIcons.generated.ts
//
// An app with no entry in Simple Icons has `null` in the table and keeps the letter tile.
// `desktop/test/app-icons.test.mjs` and `mobile/tests/app-icons.test.ts` check the two files are
// identical and that every catalog id is in the table. Run: node desktop/scripts/build-app-icons.mjs
//
// To update, pick a release that is at least two weeks old (npm view simple-icons time), change
// VERSION, run this, and read the diff. The brand marks belong to their owners; Simple Icons' own
// DISCLAIMER.md says how they may be used.

import { execFileSync } from "node:child_process";
import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { CATALOG } from "../desktop/mcp-catalog.mjs";

export const VERSION = "16.37.0"; // published 2026-11-08
export const LICENSE = "CC0-1.0";

/** Catalog id → Simple Icons slug, or null where Simple Icons has no mark for the brand (13 as of 16.37.0). */
export const SLUGS = {
  context7: null,
  deepwiki: null,
  exa: null,
  excalidraw: "excalidraw",
  huggingface: "huggingface",
  "aws-knowledge": null, // Simple Icons dropped the AWS mark
  coingecko: null,
  clerk: "clerk",
  notion: "notion",
  linear: "linear",
  atlassian: "atlassian",
  todoist: "todoist",
  clickup: "clickup",
  trello: "trello",
  dropbox: "dropbox",
  coda: "coda",
  granola: null,
  calendly: "calendly",
  fastmail: null,
  readwise: null,
  ynab: null,
  gitlab: "gitlab",
  sentry: "sentry",
  vercel: "vercel",
  cloudflare: "cloudflare",
  supabase: "supabase",
  neon: "neon",
  prisma: "prisma",
  stripe: "stripe",
  datadog: "datadog",
  grafana: "grafana",
  sanity: "sanity",
  postman: "postman",
  mixpanel: "mixpanel",
  posthog: "posthog",
  revenuecat: "revenuecat",
  tavily: null,
  canva: null,
  miro: "miro",
  webflow: "webflow",
  fal: null,
  render: "render",
  figma: "figma",
  obsidian: "obsidian",
  firecrawl: null,
  "brave-search": "brave",
  airtable: "airtable",
  resend: "resend",
  hubspot: "hubspot",
};

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const TARGETS = [join(root, "mobile/src/data/appIcons.generated.ts"), join(root, "desktop/src/appIcons.generated.ts")];

function download() {
  const temp = mkdtempSync(join(tmpdir(), "simple-icons-"));
  execFileSync("npm", ["pack", "simple-icons@" + VERSION, "--silent", "--pack-destination", temp], { cwd: temp, stdio: ["ignore", "ignore", "inherit"] });
  execFileSync("tar", ["-xzf", join(temp, "simple-icons-" + VERSION + ".tgz"), "-C", temp]);
  return temp;
}

function build(folder) {
  const pkg = JSON.parse(readFileSync(join(folder, "package", "package.json"), "utf8"));
  if (pkg.version !== VERSION || pkg.license !== LICENSE) throw new Error("Unexpected release: " + pkg.version + " " + pkg.license);
  const data = new Map(JSON.parse(readFileSync(join(folder, "package", "data", "simple-icons.json"), "utf8")).map((icon) => [icon.slug, icon]));
  const out = {};
  for (const entry of CATALOG) {
    if (!(entry.id in SLUGS)) throw new Error("Add " + entry.id + " to SLUGS in desktop/scripts/build-app-icons.mjs (a Simple Icons slug, or null).");
    const slug = SLUGS[entry.id];
    if (!slug) continue;
    const icon = data.get(slug);
    if (!icon) throw new Error("Simple Icons " + VERSION + " has no " + slug);
    const svg = readFileSync(join(folder, "package", "icons", slug + ".svg"), "utf8");
    const path = /<path d="([^"]+)"/.exec(svg)?.[1];
    if (!path || /<path[^>]*<path/.test(svg)) throw new Error(slug + ".svg is not one path");
    if (!/^[0-9A-F]{6}$/.test(icon.hex)) throw new Error(slug + " has no hex color");
    out[entry.id] = { path, hex: icon.hex, title: icon.title };
  }
  for (const id of Object.keys(SLUGS)) if (!CATALOG.some((entry) => entry.id === id)) throw new Error(id + " is in SLUGS but not in the catalog");
  return out;
}

function render(icons) {
  const lines = Object.entries(icons).map(([id, icon]) => `  ${JSON.stringify(id)}: { path: ${JSON.stringify(icon.path)}, hex: ${JSON.stringify(icon.hex)}, title: ${JSON.stringify(icon.title)} },`);
  return [
    "// Generated by desktop/scripts/build-app-icons.mjs: do not edit. The same file is in mobile/src/data and desktop/src.",
    "// Brand marks from Simple Icons (https://simpleicons.org), " + LICENSE + ". The marks belong to their owners.",
    "",
    `export const APP_ICONS_SOURCE = { name: "Simple Icons", version: ${JSON.stringify(VERSION)}, license: ${JSON.stringify(LICENSE)}, url: "https://github.com/simple-icons/simple-icons" } as const;`,
    "",
    "/** One monochrome path on a 24 × 24 grid, the brand's official color (six hex digits, no #) and its name. */",
    "export type AppIcon = { path: string; hex: string; title: string };",
    "",
    "/** The marks, keyed by catalog id. An app with no mark is not here. */",
    "export const APP_ICONS: Record<string, AppIcon> = {",
    ...lines,
    "};",
    "",
  ].join("\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const folder = download();
  try {
    const icons = build(folder);
    const text = render(icons);
    for (const target of TARGETS) {
      mkdirSync(dirname(target), { recursive: true });
      writeFileSync(target, text);
    }
    const missing = CATALOG.filter((entry) => !icons[entry.id]).map((entry) => entry.id);
    console.log("Simple Icons " + VERSION + ": " + Object.keys(icons).length + " icons written to " + TARGETS.length + " files.");
    console.log("Letter tiles: " + missing.join(", "));
  } finally {
    rmSync(folder, { recursive: true, force: true });
  }
}
