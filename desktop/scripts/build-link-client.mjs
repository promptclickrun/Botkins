// Makes desktop/remote/link-client.mjs: the link's client library, for this app as a client of
// another computer's Botkins (desktop/link/CONTRACT.md).
//
// The library is the phone app's (`src/link/` in its repo). It is copied here as it is, into
// desktop/remote/client/, and never edited: a change is made there, then this script is run again.
// The main process is plain JavaScript, so the copy is compiled into one file together with the
// small crypto packages it uses (taken from the phone repo's own node_modules, so both apps run
// the same versions). The file says which sources it was made from; test/remote.test.mjs checks
// that it still matches the copy.
//
//   node scripts/build-link-client.mjs                  compile the approved local copy
//   node scripts/build-link-client.mjs ../botkins        import the approved phone sources, then compile
import { createHash } from "node:crypto";
import assert from "node:assert/strict";
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const phone = resolve(process.argv[2] ?? join(root, "..", "botkins"));
const from = join(phone, "src", "link");
const copy = join(root, "desktop", "remote", "client");
const out = join(root, "desktop", "remote", "link-client.mjs");
const approved = JSON.parse(readFileSync(join(root, "desktop/remote/client-sources.json"), "utf8"));
const source = process.argv[2] ? from : copy;
const names = readdirSync(source).filter((name) => name.endsWith(".ts")).sort();
assert.deepEqual(names, Object.keys(approved).sort(), "The approved link client file list changed.");
const files = names.map((name) => {
  const bytes = readFileSync(join(source, name));
  assert.equal(createHash("sha256").update(bytes).digest("hex"), approved[name], "Unapproved link client source: " + name);
  return { name, bytes };
});

/** One digest over the copied sources, in name order. */
export function sourcesDigest(folder) {
  const hash = createHash("sha256");
  for (const name of readdirSync(folder).filter((file) => file.endsWith(".ts")).sort()) hash.update(name + "\n").update(readFileSync(join(folder, name)));
  return hash.digest("hex");
}

if (source !== copy) {
  mkdirSync(copy, { recursive: true });
  for (const { name, bytes } of files) writeFileSync(join(copy, name), bytes);
}
const digest = sourcesDigest(copy);
const entry = [
  'export { PROTOCOL, LinkClient, LinkError, findHost, pair } from "./client/client";',
  'export { isRelayHost, relayFetch } from "./client/relay";',
  'export { DEFAULT_PORT, formatCode, normalizeHost, parsePairingUrl } from "./client/pairing";',
].join("\n");
const result = await build({
  stdin: { contents: entry, resolveDir: join(root, "desktop", "remote"), loader: "ts", sourcefile: "link-client.ts" },
  bundle: true,
  format: "esm",
  platform: "neutral",
  target: "es2022",
  mainFields: ["module", "main"],
  conditions: ["import", "default"],
  nodePaths: [join(phone, "node_modules")],
  write: false,
  legalComments: "none",
});
const banner = [
  "// GENERATED by scripts/build-link-client.mjs. Do not edit: change the phone app's src/link/, then run the script again.",
  "// The link's client library (desktop/link/CONTRACT.md), compiled from desktop/remote/client/ with its crypto packages.",
  "// sources: " + digest,
  "",
].join("\n");
writeFileSync(out, banner + result.outputFiles[0].text);
console.log("wrote " + out.replace(root + "/", "") + " (" + Math.round(result.outputFiles[0].text.length / 1024) + " KB) from sources " + digest.slice(0, 12));
