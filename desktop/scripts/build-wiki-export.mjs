// Makes desktop/generated/wiki-export-doc.mjs: the wiki's export document for the main process.
//
// The window lays a wiki export out itself (src/wikiExportDoc.tsx) and hands the main process the
// finished page. A paired phone, or another computer using this one, has no copy of that code, so
// for them the main process lays the same document out: this script compiles the window's own
// module, with what it draws with, into one file the main process can load. Nothing is rewritten
// by hand, so both make the same document.
//
// The file names the sources it was made from; test/phonefiles.test.mjs fails when one of them
// has changed since. Run again after changing how an export looks:
//   node scripts/build-wiki-export.mjs
import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const out = join(root, "desktop", "generated", "wiki-export-doc.mjs");

/** One digest over the named source files, in name order. */
export function sourcesDigest(files, base = root) {
  const hash = createHash("sha256");
  for (const name of [...files].sort()) hash.update(name + "\n").update(readFileSync(join(base, name)));
  return hash.digest("hex");
}

const result = await build({
  entryPoints: [join(root, "src", "wikiExportDoc.tsx")],
  bundle: true,
  format: "esm",
  platform: "node",
  target: "node20",
  jsx: "automatic",
  // The page's styles and its bridge to the main process have no part in a document made here.
  loader: { ".css": "empty" },
  define: { "window.botkins": "undefined", "process.env.NODE_ENV": '"production"' },
  // Packages written for `require` ask for Node's own modules that way.
  banner: { js: 'import { createRequire as __createRequire } from "node:module";\nconst require = __createRequire(import.meta.url);' },
  metafile: true,
  write: false,
  legalComments: "none",
});
const sources = Object.keys(result.metafile.inputs).map((file) => relative(root, resolve(root, file))).filter((file) => file.startsWith("src/"));
const head = [
  "// GENERATED by scripts/build-wiki-export.mjs. Do not edit: change src/wikiExportDoc.tsx (or what it uses), then run the script again.",
  "// The wiki's export document (exportDocument), compiled for the main process.",
  "// from: " + sources.sort().join(", "),
  "// sources: " + sourcesDigest(sources),
  "",
].join("\n");
mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, head + result.outputFiles[0].text);
console.log("wrote " + relative(root, out) + " (" + Math.round(result.outputFiles[0].text.length / 1024) + " KB) from " + sources.length + " sources");
