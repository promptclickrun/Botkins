/*
 * Turns files into a C++ source of byte arrays, as a board's build embeds its files: how the host
 * build hands the fonts to the screen. Needs nothing but a C compiler (no xxd).
 *
 *   embed <out.cpp> <symbol> <file> [<symbol> <file> ...]
 *
 * For each pair: `extern const unsigned char <symbol>[]` and `extern const unsigned long <symbol>_size`.
 */
#include <stdio.h>

int main(int argc, char** argv) {
  if (argc < 4 || argc % 2 != 0) {
    fprintf(stderr, "usage: embed <out.cpp> <symbol> <file> [<symbol> <file> ...]\n");
    return 2;
  }
  FILE* out = fopen(argv[1], "w");
  if (!out) {
    perror(argv[1]);
    return 1;
  }
  fprintf(out, "// Generated by firmware/host/embed.c. Do not edit.\n");
  for (int i = 2; i + 1 < argc; i += 2) {
    FILE* in = fopen(argv[i + 1], "rb");
    if (!in) {
      perror(argv[i + 1]);
      fclose(out);
      return 1;
    }
    fprintf(out, "extern const unsigned char %s[];\nconst unsigned char %s[] = {", argv[i], argv[i]);
    unsigned long size = 0;
    int c;
    while ((c = fgetc(in)) != EOF) {
      fprintf(out, "%s%d,", size % 32 == 0 ? "\n" : "", c);
      size++;
    }
    fclose(in);
    fprintf(out, "\n};\nextern const unsigned long %s_size;\nconst unsigned long %s_size = %luUL;\n", argv[i], argv[i], size);
  }
  return fclose(out) == 0 ? 0 : 1;
}
