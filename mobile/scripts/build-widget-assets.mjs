#!/usr/bin/env node
// Builds what the Live Activity extension draws a Botkin from (targets/widgets):
//   targets/widgets/assets/<head>-<palette>.png   each head in each kit palette, small, without eyes
//   targets/widgets/BotkinHeads.swift             where each head's eyes go, and its own eye color
// It reads the design kit directly (design/botkins-kit), like scripts/build-botkins.mjs, and needs
// macOS (the SVGs are drawn by AppKit).
//   node scripts/build-widget-assets.mjs
import { execFileSync } from "node:child_process";
import { mkdirSync, mkdtempSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { tmpdir } from "node:os";
import { join } from "node:path";

const require = createRequire(import.meta.url);
const kit = require("../design/botkins-kit/customize.js");
const SIZE = 132; // 44 points at 3x
const OUT = "targets/widgets/assets";
const work = mkdtempSync(join(tmpdir(), "botkins-widget-"));
const renderer = join(work, "render-svg");
execFileSync("swiftc", ["-O", "scripts/render-svg.swift", "-o", renderer], { stdio: "inherit" });
rmSync(OUT, { recursive: true, force: true });
mkdirSync(OUT, { recursive: true });

const heads = [];
for (const file of readdirSync("design/botkins-kit/avatars").filter((name) => name.endsWith(".svg")).sort()) {
  const id = file.replace(/\.svg$/, "");
  const source = readFileSync(join("design/botkins-kit/avatars", file), "utf8");
  const [, tx, ty, scale] = /<g transform="translate\(([\d.-]+) ([\d.-]+)\) scale\(([\d.-]+)\)">/.exec(source).map(Number);
  const [, anchors, ink] = /<g data-layer="eyes" data-anchors="([^"]+)" fill="(#[0-9a-fA-F]{6})"/.exec(source);
  const [left, right, y] = anchors.split(",").map(Number);
  heads.push({ id, tx, ty, scale, left, right, y, ink });
  for (const palette of Object.keys(kit.palettes)) {
    const art = kit.render(source, "Oval", palette, { blink: false }).replace(/<g data-layer="eyes"[\s\S]*?<\/g>/, "");
    const base = join(work, id + "-" + palette.toLowerCase());
    writeFileSync(base + ".svg", art);
    execFileSync(renderer, [base + ".svg", join(OUT, id + "-" + palette.toLowerCase() + ".png"), String(SIZE)]);
  }
  process.stdout.write(".");
}

const inks = Object.entries(kit.palettes).filter(([, colors]) => colors).map(([name, colors]) => `  "${name.toLowerCase()}": "${colors[3]}",`);
writeFileSync(
  "targets/widgets/BotkinHeads.swift",
  [
    "// Generated by scripts/build-widget-assets.mjs from design/botkins-kit. Do not edit by hand.",
    "import Foundation",
    "",
    "/// Where a head's eyes sit (in the head's own units, placed by tx, ty and scale on a 256 canvas) and its own eye color.",
    "struct BotkinHead {",
    "  let tx: Double, ty: Double, scale: Double, left: Double, right: Double, y: Double",
    "  let ink: String",
    "}",
    "",
    "let botkinHeads: [String: BotkinHead] = [",
    ...heads.map((h) => `  "${h.id}": BotkinHead(tx: ${h.tx}, ty: ${h.ty}, scale: ${h.scale}, left: ${h.left}, right: ${h.right}, y: ${h.y}, ink: "${h.ink}"),`),
    "]",
    "",
    "/// The eye color of each kit palette. Original keeps the head's own.",
    "let botkinPaletteInk: [String: String] = [",
    ...inks,
    "]",
    "",
  ].join("\n"),
);
rmSync(work, { recursive: true, force: true });
console.log("\n" + heads.length + " heads × " + Object.keys(kit.palettes).length + " palettes → " + OUT);
